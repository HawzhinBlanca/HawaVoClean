"""Generate SYNTHETIC test datasets with honest manifests.

Every waveform here is generated by ``generate_speech_like_waveform`` — a
harmonic tone with speech-like modulation. None of it is human speech, none
of it is Kurdish, and the manifests say so: dialect is "synthetic",
verified_by_human is false, and no transcripts are claimed. These corpora
exercise the pipeline's plumbing and the guard's spectral comparisons; they
cannot validate linguistic fidelity.
"""

import json
import sys
from pathlib import Path
from typing import Any

import soundfile as sf

from voiceclean.eval.corruption import (
    corrupt_consonant_splice,
    corrupt_hf_consonant_removal,
    corrupt_repeated_span,
    corrupt_syllable_deletion,
)
from voiceclean.hashing import hash_file

SR = 48000


def _item(
    item_id: str,
    wav_path: Path,
    duration_s: float,
    f0: float,
    degradation_type: str,
    split: str,
) -> dict[str, Any]:
    return {
        "id": item_id,
        "audio_path": str(wav_path),
        "audio_sha256": hash_file(wav_path),
        "duration_s": duration_s,
        "speaker_id": f"synthetic_f0_{int(f0)}",
        "dialect": "synthetic",
        "gender": "unknown",
        "environment": "synthetic",
        "degradation_type": degradation_type,
        "transcript_sorani": "",
        "verified_by_human": False,
        "split": split,
    }


def _write_manifest(
    directory: Path, manifest_id: str, split: str, items: list[dict[str, Any]]
) -> None:
    manifest = {
        "schema_version": 1,
        "manifest_id": manifest_id,
        "split_name": split,
        "items_count": len(items),
        "items": items,
    }
    with open(directory / "manifest.json", "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)


def generate_all_datasets() -> None:
    # Dev-only: the fixture generator lives in the repo checkout, not the
    # installed package, so the repo root must be importable.
    repo_root = Path(__file__).resolve().parents[1]
    if str(repo_root) not in sys.path:
        sys.path.insert(0, str(repo_root))
    from tests.fixtures.generate_fixtures import generate_speech_like_waveform

    base_data = Path("data")
    base_data.mkdir(parents=True, exist_ok=True)

    # 1. Calibration split: four synthetic tones at distinct fundamentals
    calib_dir = base_data / "calibration"
    calib_audio = calib_dir / "audio"
    calib_audio.mkdir(parents=True, exist_ok=True)
    calib_items = []
    for i, f0 in enumerate((130.0, 150.0, 190.0, 210.0)):
        wave = generate_speech_like_waveform(duration_s=6.0, sample_rate=SR, f0=f0)
        item_id = f"calib_synthetic_{i + 1}"
        path = calib_audio / f"{item_id}.wav"
        sf.write(str(path), wave, SR, subtype="PCM_24")
        calib_items.append(_item(item_id, path, 6.0, f0, "clean", "calibration"))
    _write_manifest(calib_dir, "calibration_split_v2", "calibration", calib_items)

    # 2. Acceptance split: four synthetic tones, one with mains hum
    acc_dir = base_data / "acceptance"
    acc_audio = acc_dir / "audio"
    acc_audio.mkdir(parents=True, exist_ok=True)
    acc_items = []
    for i, f0 in enumerate((125.0, 145.0, 185.0, 215.0)):
        wave = generate_speech_like_waveform(
            duration_s=5.0, sample_rate=SR, f0=f0, add_hum=(i == 1)
        )
        item_id = f"acc_synthetic_{i + 1}"
        path = acc_audio / f"{item_id}.wav"
        sf.write(str(path), wave, SR, subtype="PCM_24")
        acc_items.append(
            _item(item_id, path, 5.0, f0, "electrical_hum" if i == 1 else "clean", "acceptance")
        )
    _write_manifest(acc_dir, "acceptance_split_v2", "acceptance", acc_items)

    # 3. Corruption counterexamples: known-bad renderings of a clean base
    corr_dir = base_data / "corruption"
    corr_audio = corr_dir / "audio"
    corr_audio.mkdir(parents=True, exist_ok=True)
    clean_base = generate_speech_like_waveform(duration_s=6.0, sample_rate=SR, f0=150.0)
    corruptions = [
        (
            "splice",
            corrupt_consonant_splice(clean_base, SR, start_time_s=1.0, cut_duration_ms=100.0),
        ),
        (
            "deletion",
            corrupt_syllable_deletion(clean_base, SR, start_time_s=3.0, deletion_ms=250.0),
        ),
        ("repeat", corrupt_repeated_span(clean_base, SR, start_time_s=1.5, span_ms=300.0)),
        ("muffled", corrupt_hf_consonant_removal(clean_base, SR, cutoff_hz=1200.0)),
    ]
    corr_items = []
    for name, wave in corruptions:
        item_id = f"corr_{name}"
        path = corr_audio / f"{item_id}.wav"
        sf.write(str(path), wave, SR, subtype="PCM_24")
        corr_items.append(
            _item(item_id, path, float(len(wave) / SR), 150.0, f"corrupted_{name}", "corruption")
        )
    _write_manifest(corr_dir, "corruption_split_v2", "corruption", corr_items)

    print("Generated synthetic datasets in data/ (calibration, acceptance, corruption).")
    print("These are tones, not speech; the manifests carry no human-verification claims.")


if __name__ == "__main__":
    generate_all_datasets()
